-- AttendEase: Student Attendance Management System
-- Run this entire script in Supabase Dashboard -> SQL Editor.
-- MVP note: this is a classroom demonstration app with no user login.
-- Do not expose the server-only key or deploy this publicly without adding admin authentication.

create table if not exists public.students (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 1 and 100),
  roll_number text not null unique check (char_length(trim(roll_number)) between 1 and 30),
  created_at timestamptz not null default now()
);

create table if not exists public.attendance (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(id) on delete cascade,
  attendance_date date not null,
  status text not null check (status in ('present', 'absent')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint attendance_one_per_student_per_day unique (student_id, attendance_date)
);

create index if not exists attendance_date_idx on public.attendance(attendance_date);
create index if not exists attendance_student_date_idx on public.attendance(student_id, attendance_date);

create or replace function public.set_attendance_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists attendance_updated_at_trigger on public.attendance;
create trigger attendance_updated_at_trigger
before update on public.attendance
for each row execute function public.set_attendance_updated_at();

-- The backend uses a server-only Supabase secret/service_role key and performs
-- all access through Express validation. Keep RLS enabled so browser-facing
-- anon/authenticated roles cannot access these tables directly.
alter table public.students enable row level security;
alter table public.attendance enable row level security;

-- Intentionally no anon/authenticated policies: direct browser access is denied.
-- The server-only key bypasses RLS, so Express routes must remain protected.
-- This MVP has no login and is intended for local classroom demos only.

